local _, QFXAM = ...
local languages = { AUTO = true, enUS = true, zhCN = true, zhTW = true }

function QFXAM.GetLanguage()
    local db = QFXAM.db or rawget(_G, "QFXAddonManagerDB")
    local language = type(db) == "table" and type(db.ui) == "table" and db.ui.language
    return languages[language] and language or "AUTO"
end

function QFXAM.ResolveLocale(language)
    if language == "zhCN" or language == "zhTW" or language == "enUS" then return language end
    local locale = GetLocale and GetLocale() or "enUS"
    return (locale == "zhCN" or locale == "zhTW") and locale or "enUS"
end

-- Static titles and lazy modules share one language for the whole session.
local activeLocale = QFXAM.ResolveLocale(QFXAM.GetLanguage())
function QFXAM.GetLocale() return activeLocale end

